"""Redis-backed sessions (SPEC step 4): an httpOnly, Secure, SameSite=Lax cookie holding a
random id, plus a per-session CSRF token that every state-changing request must echo in the
`X-CSRF-Token` header.

The session id is always generated by the server at login or registration (never adopted from
the request), and any session the request already carried is destroyed first: no fixation.
No timestamps are stored; expiry is the Redis TTL.
"""

from __future__ import annotations

import hmac
import json
import secrets
import uuid
from dataclasses import dataclass
from typing import Annotated

from fastapi import Depends, HTTPException, Request, Response
from sqlalchemy.orm import Session

from api.auth.hashing import token_key
from api.auth.store import Store, get_store
from api.config import get_settings
from api.db.models import Account
from api.db.session import get_session

CSRF_HEADER = "x-csrf-token"
SAFE_METHODS = frozenset({"GET", "HEAD", "OPTIONS"})
#: Unsafe-method endpoints that never act on the session cookie's authority: the steps before
#: a session exists, and the stateless verifier. Everything else needs the CSRF header whenever
#: a live session cookie is sent.
CSRF_EXEMPT_PATHS = frozenset(
    {
        "/auth/email",
        "/auth/verify-code",
        "/auth/register",
        "/auth/login",
        "/auth/password-reset/start",
        "/auth/password-reset/finish",
        "/verify",
    }
)


@dataclass(frozen=True)
class SessionData:
    sid: str
    account_id: uuid.UUID
    csrf_token: str


def cookie_name() -> str:
    # The __Host- prefix makes browsers refuse the cookie unless it is Secure, host-only and
    # Path=/; it cannot be used over plain http in local development.
    return "__Host-qp_session" if get_settings().session_cookie_secure else "qp_session"


def _session_key(sid: str) -> str:
    return f"sess:{token_key(sid)}"


def _index_key(account_id: uuid.UUID) -> str:
    return f"sess-index:{account_id}"


def create_session(store: Store, account_id: uuid.UUID) -> SessionData:
    ttl = get_settings().session_ttl_seconds
    data = SessionData(
        sid=secrets.token_urlsafe(32),
        account_id=account_id,
        csrf_token=secrets.token_urlsafe(32),
    )
    record = json.dumps({"account_id": str(account_id), "csrf": data.csrf_token})
    store.put(_session_key(data.sid), record, ttl)
    store.sadd(_index_key(account_id), _session_key(data.sid), ttl)
    return data


def load_session(store: Store, sid: str) -> SessionData | None:
    raw = store.get(_session_key(sid))
    if raw is None:
        return None
    record = json.loads(raw)
    return SessionData(
        sid=sid, account_id=uuid.UUID(record["account_id"]), csrf_token=record["csrf"]
    )


def destroy_session(store: Store, session: SessionData) -> None:
    store.delete(_session_key(session.sid))
    store.srem(_index_key(session.account_id), _session_key(session.sid))


def destroy_account_sessions(
    store: Store, account_id: uuid.UUID, *, keep: SessionData | None = None
) -> None:
    """End every session of the account (except `keep`)."""
    kept = _session_key(keep.sid) if keep else None
    for key in store.smembers(_index_key(account_id)):
        if key != kept:
            store.delete(key)
            store.srem(_index_key(account_id), key)


def set_session_cookie(response: Response, session: SessionData) -> None:
    settings = get_settings()
    response.set_cookie(
        cookie_name(),
        session.sid,
        max_age=settings.session_ttl_seconds,
        path="/",
        httponly=True,
        secure=settings.session_cookie_secure,
        samesite="lax",
    )
    response.headers["Cache-Control"] = "no-store"


def clear_session_cookie(response: Response) -> None:
    response.delete_cookie(
        cookie_name(),
        path="/",
        httponly=True,
        secure=get_settings().session_cookie_secure,
        samesite="lax",
    )


def optional_session(
    request: Request, store: Annotated[Store, Depends(get_store)]
) -> SessionData | None:
    sid = request.cookies.get(cookie_name())
    return load_session(store, sid) if sid else None


def csrf_guard(request: Request, store: Annotated[Store, Depends(get_store)]) -> None:
    """Application-wide dependency (api.main): a state-changing request that carries a live
    session cookie must also carry that session's CSRF token."""
    if request.method in SAFE_METHODS or request.url.path in CSRF_EXEMPT_PATHS:
        return
    sid = request.cookies.get(cookie_name())
    if not sid:
        return
    session = load_session(store, sid)
    if session is None:
        return
    sent = request.headers.get(CSRF_HEADER, "")
    if not hmac.compare_digest(sent.encode(), session.csrf_token.encode()):
        raise HTTPException(status_code=403, detail="Missing or invalid CSRF token.")


def require_session(
    session: Annotated[SessionData | None, Depends(optional_session)],
) -> SessionData:
    if session is None:
        raise HTTPException(status_code=401, detail="Log in to continue.")
    return session


def current_account(
    session: Annotated[SessionData, Depends(require_session)],
    db: Annotated[Session, Depends(get_session)],
    store: Annotated[Store, Depends(get_store)],
) -> Account:
    """Dependency for every endpoint that needs a logged-in account."""
    account = db.get(Account, session.account_id)
    if account is None:
        destroy_session(store, session)
        raise HTTPException(status_code=401, detail="Log in to continue.")
    return account
