"""Builds the eval sets in this folder from the hand-verified 2026-27 seed (SPEC "Evals").

    uv run python evals/build_sets.py

Every reference answer is copied from the seed (a course's `prereq_text`, `terms_offered` or
description), never written by hand, so the sets invent no catalog facts. The output is
deterministic; commit the YAML files it writes. Off-topic questions, confirmation phrases and
injection posts are written here by hand: they state nothing about courses.
"""

from __future__ import annotations

import itertools
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve().parent
SEED = HERE.parent / "data" / "seed" / "2026-27"
YEAR = "2026-27"
