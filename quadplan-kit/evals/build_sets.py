def a1_profiles() -> list[dict[str, Any]]:
    out = []
    for i, (programs_, goals) in enumerate(itertools.product(PROGRAM_SETS, goal_sets())):
        interests = INTERESTS[i % len(INTERESTS)]
        out.append(
            {
                "id": f"a1-{i + 1:02d}",
                "request": {
                    "plan": {
                        "catalog_year": YEAR,
                        "entry_term": ENTRY,
                        "placements": ["MATH 15100"],
                        "programs": [{"program_id": p} for p in programs_],
                        "goals": goals,
                    },
                    "scope": "whole",
                    "goals": goals,
                    "interests": interests,
                    "load": [-0.5, 0.0, 0.5][i % 3],
                    "variants": 2,
                },
            }
        )
    return out


