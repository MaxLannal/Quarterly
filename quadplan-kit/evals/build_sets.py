QUARTER_NAMES = {"AU": "Autumn", "WI": "Winter", "SP": "Spring", "SU": "Summer"}
HEADER = "# Generated by evals/build_sets.py from data/seed/2026-27. Do not edit by hand.\n"


def courses() -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for path in sorted((SEED / "courses").glob("*.yaml")):
        out += yaml.safe_load(path.read_text())["courses"]
    return [c for c in out if c.get("units", 100) >= 100]


def programs() -> dict[str, str]:
    out = {}
    for path in sorted((SEED / "programs").glob("*.yaml")):
        data = yaml.safe_load(path.read_text())
        out[data["id"]] = data["name"]
    return out


def pick(items: list[dict[str, Any]], n: int, subjects: tuple[str, ...]) -> list[dict[str, Any]]:
    """`n` courses spread over `subjects`, in a stable order."""
    by_subject = {s: [c for c in items if c["code"].startswith(f"{s} ")] for s in subjects}
    chosen: list[dict[str, Any]] = []
    for row in itertools.zip_longest(*by_subject.values()):
        chosen += [c for c in row if c is not None]
        if len(chosen) >= n:
            break
    return chosen[:n]


